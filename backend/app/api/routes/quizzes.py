@router.delete("/{quiz_id}", summary="Delete Quiz and Associated Questions")
async def delete_quiz(
    quiz_id: str,
    current_user: AuthenticatedUser = Depends(get_current_user),
) -> Dict[str, Any]:
    """
    Deletes a user's quiz. Questions cascade-delete automatically via foreign key.
    """
    client = supabase_service.get_user_client(current_user.token)
    try:
        # Check quiz existence & ownership
        quiz_res = (
            client.from_("quizzes")
            .select("id")
            .eq("id", quiz_id)
            .eq("user_id", current_user.id)
            .execute()
        )
        if not quiz_res.data:
            raise HTTPException(
                status_code=status.HTTP_404_NOT_FOUND,
                detail="Quiz not found or access denied.",
            )

        # Delete quiz
        client.from_("quizzes").delete().eq("id", quiz_id).eq("user_id", current_user.id).execute()

        return {
            "message": "Quiz deleted successfully.",
            "id": quiz_id,
        }
    except HTTPException:
        raise
    except Exception as e:
        _handle_supabase_error(e)
